//////////////////////////////////////////////////////////////////////////////////
// font_rom.v
// 8x8 pixel bitmap font, 32 character slots.
//
// Address: {char_index[4:0], row[2:0]}  -> 8-bit address
// Output : 8-bit row bitmap  (bit 7 = leftmost pixel)
//
// Character index table
// ---------------------
//  0- 9  : digits '0'..'9'
