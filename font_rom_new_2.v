//  15     : ' '  (space)
//  16     : 'Q'  (quantisation mode label)
//  17     : '.'  (decimal point in Q-format names)
//  18     : 'I'  (INT8 mode label)
//  19     : 'N'  (INT8 mode label)
//  20     : 'T'  (INT8 mode label)
//  21     : 'x' (multiply sign)
//  22-31  : reserved (blank)
//////////////////////////////////////////////////////////////////////////////////

